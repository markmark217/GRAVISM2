"""
Scientific Results Exporter
===========================

Exports simulation results, image positions, and experiment records to:
- JSON format
- CSV numerical tabular data
- Markdown research report
"""

import io
import json
import pandas as pd
from typing import Dict, Any


def export_to_json(sim_data: Dict[str, Any]) -> str:
    """Format simulation parameters and summary outputs to JSON."""
    exportable = {}
    for k, v in sim_data.items():
        if isinstance(v, (int, float, str, bool, list)):
            exportable[k] = v
        elif isinstance(v, tuple):
            exportable[k] = list(v)

    return json.dumps(exportable, indent=2)


def export_images_to_csv(images_list: list) -> str:
    """Export predicted image positions and properties to CSV string."""
    df = pd.DataFrame(images_list)
    return df.to_csv(index=False)


def generate_experiment_markdown_report(title: str,
                                        hypothesis: str,
                                        model_type: str,
                                        parameters: Dict[str, Any],
                                        results: Dict[str, Any],
                                        conclusions: str) -> str:
    """Generate a formatted scientific research experiment report."""
    md = f"""# GRAVISIM Scientific Experiment Report: {title}

**Date Generated:** {pd.Timestamp.now().strftime('%Y-%m-%d %H:%M:%S')}  
**Model Type:** {model_type}

---

## 1. Hypothesis
{hypothesis}

## 2. Simulation Parameters
| Parameter | Value |
|---|---|
"""
    for k, v in parameters.items():
        md += f"| {k} | {v} |\n"

    md += """
## 3. Numerical & Physical Results
| Metric | Value |
|---|---|
"""
    for k, v in results.items():
        if isinstance(v, (int, float, str, bool)):
            md += f"| {k} | {v} |\n"

    md += f"""
## 4. Discussion & Scientific Conclusions
{conclusions}

---
*Generated by GRAVISIM: Interactive Gravitational Lensing Simulation and Computational Physics Laboratory*
"""
    return md

